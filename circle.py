import math


def area(r):
    '''
        Данная функция принимает на вход значение r - радиус окружности
        Возвращает площадь окружности заданной данным радиусом
    '''
    return math.pi * r * r


def perimeter(r):
    '''
        Данная функция принимает на вход значение r - радиус окружности
        Возвращает периметр окружности заданной данным радиусом
    '''
    return 2 * math.pi * r

